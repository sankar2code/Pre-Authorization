export const LANGS = [
  { key: 'en', label: 'English', short: 'EN', speech: 'en-US', locale: 'en-US' },
  { key: 'es', label: 'Español', short: 'ES', speech: 'es-US', locale: 'es-US' },
]

export function makeT(lang) {
  const dict = STRINGS[lang] ?? STRINGS.en
  const t = (key, vars) => {
    let s = dict[key] ?? STRINGS.en[key] ?? key
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v)
    return s
  }
  const L = (value) => (value && typeof value === 'object' ? (value[lang] ?? value.en) : value)
  // Sentence-start form: "el consultorio…" -> "El consultorio…"
  const cap = (s) => (s ? s[0].toUpperCase() + s.slice(1) : s)
  const locale = LANGS.find((l) => l.key === lang)?.locale ?? 'en-US'
  const money = (n) =>
    new Intl.NumberFormat(locale, { style: 'currency', currency: 'USD', maximumFractionDigits: n % 1 ? 2 : 0, minimumFractionDigits: n % 1 ? 2 : 0 }).format(n)
  const date = (d, opts = { weekday: 'short', month: 'short', day: 'numeric', year: 'numeric' }) =>
    new Intl.DateTimeFormat(locale, opts).format(d)
  return { t, L, cap, money, date, lang }
}

export function formatWhen(fmt, atMs, fallback) {
  if (!atMs) return fallback ?? ''
  return fmt.date(new Date(atMs), { month: 'short', day: 'numeric', hour: 'numeric', minute: '2-digit' })
}

// "6 monthly payments of $143.34" / "At my appointment"
export function planLabel(fmt, payment) {
  if (payment.option === 'service') return fmt.t('payLaterAtService')
  return fmt.t('payLaterMonths', { n: payment.option, amount: fmt.money(payment.monthly) })
}
